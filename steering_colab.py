import math, random

random.seed(1)

def circle_samples(cx, cy, radius, segments):
    """segments: [(градусов_в_секунду, секунд), ...]; скорость None = стик в покое. Кадры 50 Гц."""
    out, t, angle = [], 0, 0.0
    for speed, seconds in segments:
        for _ in range(int(seconds * 50)):
            noise = random.randint(-2, 2), random.randint(-2, 2)
            if speed is None:
                x, y = cx + noise[0], cy + noise[1]
            else:
                angle += speed / 50
                x = cx + radius * math.cos(math.radians(angle)) + noise[0]
                y = cy + radius * math.sin(math.radians(angle)) + noise[1]
            out.append((t, max(0, min(4095, round(x))), max(0, min(4095, round(y)))))
            t += 20
    return out

