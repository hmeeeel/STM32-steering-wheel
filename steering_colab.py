OLD_FORMAT = re.compile(r"^X:\s*(\d+)\s*,\s*Y:\s*(\d+)")


def parse_samples(raw, period_ms=100):
    """Строки -> список (время_мс, X, Y). Битые и чужие строки пропускаются."""
    samples, bad = [], 0
    for line in raw.splitlines():
        line = line.strip()
        if not line:
            continue
        if line.startswith("$"):
            try:
                tel = parse_telemetry(line.encode("ascii", "ignore"))
                samples.append((tel.t_ms, tel.x, tel.y))
            except ParseError:
                bad += 1
            continue
        m = OLD_FORMAT.match(line)
        if m:
            samples.append((len(samples) * period_ms, int(m[1]), int(m[2])))
        else:
            bad += 1
    return samples, bad


def replay(samples, center=None):
    """Прогоняет значения через ту же модель, что стоит в steering_console.py."""
    model = SteeringModel(SteeringConfig())
    if center is not None:
        model.set_center(*center)
    servo = ServoMapper(ServoConfig(), model.cfg.max_wheel_deg)
    rows = []
    for t_ms, x, y in samples:
        st = model.update(t_ms, x, y)
        rows.append({
            "t, c": t_ms / 1000, "X": x, "Y": y,
            "калибровка": st.calibrating, "стик взят": st.taken,
            "угол стика, °": st.stick_deg, "руль, °": st.steer_deg,
            "колёса, °": st.wheel_deg, "серво, мкс": servo.pulse_us(st.wheel_deg),
        })
    return pd.DataFrame(rows)


